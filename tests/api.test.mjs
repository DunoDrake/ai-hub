import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fixture } from './helpers.mjs';

test('HTTP/CLI integration: review, counters, dependencies, gates and compatibility', async function (t) {
  var f = await fixture(); t.after(f.cleanup);
  var project = (await f.api('POST', '/api/projects', { path: f.repo, name: 'Workflow QA' })).project;
  var api = '/api/projects/' + project.id;
  await f.api('POST', api + '/init', { prefix: 'QA' });
  var board = await f.api('GET', api + '/board');
  assert.equal(board.workflowEnabled, true);
  assert.deepEqual(board.statuses, ['To Do', 'In Progress', 'Review', 'Done', 'Wontfix', 'Closed']);
  await f.backlog(['milestone', 'add', 'Phase 0 - QA']);
  await f.backlog(['task', 'create', 'Delivered feature', '-m', 'm-0', '-l', 'dev-medium', '--ac', 'Verified']);
  await f.backlog(['task', 'create', 'Dependent feature', '-l', 'dev-medium', '--depends-on', 'QA-1', '--ac', 'Verified']);
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Done' }, 400);
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Review' }, 400);
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'In Progress' });
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Review', expectedStatus: 'To Do', mode: 'ai', reviewer: '@gpt-review', note: 'Review requested' }, 400);
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Review', mode: 'ai', reviewer: '@gpt-review', note: 'Review requested' });
  board = await f.api('GET', api + '/board');
  assert.equal(board.tasks[0].workflow.mode, 'ai');
  assert.equal(board.health.review, 1);
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Done', mode: 'manual', reviewer: 'QA reviewer', note: 'Approved in fixture' }, 400);
  await f.backlog(['task', 'edit', 'QA-1', '--check-ac', '1']);
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Done', mode: 'manual', reviewer: 'QA reviewer', note: 'Approved in fixture' });
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Closed' });
  board = await f.api('GET', api + '/board');
  assert.equal(board.tasks.find(function (x) { return x.id === 'QA-2'; }).isReady, true);
  assert.equal(board.health.doneTotal, 1);
  assert.equal(JSON.parse(await f.phase(['next', '--provider', 'gpt', '--json'])).task.id, 'QA-2');
  await f.phase(['claim', 'QA-2', '--provider', 'gpt']);
  var summary = (await f.api('GET', '/api/projects')).projects[0].summary;
  assert.equal(summary.completedWork.total, 1);
  var metrics = await f.api('GET', api + '/metrics');
  assert.equal(metrics.phases[0].done, 1);
  assert.equal(metrics.phases[0].resolved, 1);
  assert.equal(JSON.parse(await f.phase(['gate', '0', '--json'])).pass, true);
  await f.phase(['gate', '0', '--approve', '--reviewer', 'Fixture reviewer', '--notes', 'Fixture gate']);
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'In Progress', note: 'Reopen test' });
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Wontfix' }, 400);
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Wontfix', note: 'Superseded in fixture' });
  await f.api('POST', api + '/move', { taskId: 'QA-1', status: 'Closed' });
  board = await f.api('GET', api + '/board');
  assert.equal(board.health.doneTotal, 0);
  assert.equal(board.tasks.find(function (x) { return x.id === 'QA-2'; }).isReady, true);
  metrics = await f.api('GET', api + '/metrics');
  assert.equal(metrics.phases[0].wontfix, 1);
  assert.equal(metrics.phases[0].done, 0);
  assert.equal(metrics.phases[0].completed, true);
  var csv = await (await fetch(f.url + api + '/metrics?format=csv')).text();
  assert.match(csv, /done,resolved,wontfix,unknownClosed/);
  await f.backlog(['task', 'create', 'Unknown legacy closure', '-m', 'm-0', '-l', 'dev-medium', '-s', 'Closed']);
  metrics = await f.api('GET', api + '/metrics');
  assert.equal(metrics.phases[0].unknownClosed, 1);
  await assert.rejects(f.phase(['gate', '0', '--json']), /resolutionEvidence/);
  await f.backlog(['task', 'create', 'Architecture', '-l', 'dev-high', '--ac', 'Reviewed']);
  await assert.rejects(f.phase(['claim', 'QA-4', '--provider', 'gpt']), /routing-override/);
  await f.phase(['claim', 'QA-4', '--provider', 'gpt', '--routing-override', 'Explicit test operator exception']);
  assert.match(await f.backlog(['task', 'view', 'QA-4', '--plain']), /Explicit test operator exception/);
  var forbidden = await fetch(f.url + api + '/move', { method: 'POST', body: '{}' });
  assert.equal(forbidden.status, 403);
  assert.match(fs.readFileSync(path.join(f.repo, 'AGENTS.md'), 'utf8'), /Resolve, then close/);
});

test('existing project stays legacy until opt-in; migration preserves task bytes and protocol prose', async function (t) {
  var f = await fixture(); t.after(f.cleanup);
  await f.backlog(['init', 'Legacy', '--defaults', '--no-git', '--include-remote', 'false', '--task-prefix', 'OLD', '--agent-instructions', 'none']);
  await f.backlog(['task', 'create', 'Existing', '-l', 'dev-medium']);
  fs.writeFileSync(path.join(f.repo, 'AGENTS.md'), 'Preserve this project-specific instruction.\n');
  var tasksDir = path.join(f.repo, 'backlog/tasks');
  var file = path.join(tasksDir, fs.readdirSync(tasksDir)[0]);
  var before = fs.readFileSync(file, 'utf8');
  var project = (await f.api('POST', '/api/projects', { path: f.repo })).project;
  var api = '/api/projects/' + project.id;
  assert.equal((await f.api('GET', api + '/board')).workflowEnabled, false);
  var preview = await f.api('POST', api + '/workflow', { dryRun: true });
  assert.equal(preview.dryRun, true);
  assert.equal((await f.api('GET', api + '/board')).workflowEnabled, false);
  var enabled = await f.api('POST', api + '/workflow', {});
  assert.ok(fs.existsSync(enabled.backup));
  assert.equal(fs.readFileSync(file, 'utf8'), before);
  assert.match(fs.readFileSync(path.join(f.repo, 'AGENTS.md'), 'utf8'), /^Preserve this project-specific instruction/);
  assert.equal((await f.api('GET', api + '/board')).workflowEnabled, true);
  assert.equal((await f.api('POST', api + '/workflow', {})).changed, false);
});
